"use client";

import { useMutation } from "@tanstack/react-query";
import Link from "next/link";
import { useTranslations } from "next-intl";
import { Suspense, useEffect } from "react";
import { ErrorBanner, Spinner, buttonClass } from "@/components/ui";
import { AuthFrame } from "@console/components/AuthFrame";
import { CodeForm } from "@console/components/CodeForm";
import { useErrorText } from "@console/components/useErrorText";
import { session } from "@console/lib/client";

/**
 * Sign-in, step two the first time: a secret for the authenticator app, shown once as a
 * QR code (drawn by bt-ops, so the secret meets no third party) and as text to type,
 * then the first code. Reloading the page issues a new secret; only the last one works.
 */
export default function EnrollPage() {
  const t = useTranslations("console.auth");
  const errorText = useErrorText();
  const enroll = useMutation({ mutationFn: session.enroll });
  const { mutate } = enroll;
  useEffect(() => mutate(), [mutate]);

  return (
    <AuthFrame title={t("enrollTitle")}>
      <p className="mb-4 text-ink-2">{t("enrollIntro")}</p>
      {enroll.isPending && <Spinner />}
      {enroll.isError && (
        <div className="space-y-4">
          <ErrorBanner message={errorText(enroll.error)} />
          <Link href="/login" className={buttonClass("secondary")}>
            {t("startAgain")}
          </Link>
        </div>
      )}
      {enroll.data && (
        <div className="space-y-5">
          <div
            className="mx-auto w-fit rounded-xl bg-white p-2"
            // The SVG is generated by bt-ops (segno) from the otpauth URI, no markup of ours.
            dangerouslySetInnerHTML={{ __html: enroll.data.qr_svg }}
            aria-label={t("qrLabel")}
            role="img"
          />
          <p className="text-[13px] text-ink-3">
            {t("secretLabel")}{" "}
            <code className="break-all text-ink-2">{enroll.data.secret}</code>
          </p>
          <Suspense>
            <CodeForm />
          </Suspense>
        </div>
      )}
    </AuthFrame>
  );
}
